export const getFv1DiscoveryCopy = (language) => fv1DiscoveryCopy[language] ?? fv1DiscoveryCopy.en;

export function getDiscoveryFormationStatus(copy, { exampleCount, minimum, capacity }) {
  if (exampleCount >= capacity) return copy.full;
  const remaining = Math.max(minimum - exampleCount, 0);
  if (remaining === 0) return copy.minimumReached;
  return copy.remainingToMinimum(remaining);
}
